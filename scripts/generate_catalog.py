#!/usr/bin/env python3
"""Regenerate the plugin catalog table in README.md from the manifests.

Usage:
  python3 scripts/generate_catalog.py          # rewrite README.md
  python3 scripts/generate_catalog.py --check  # exit 1 if README.md is stale
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
README = ROOT / "README.md"
START = "<!-- catalog:start (generated by scripts/generate_catalog.py, do not edit) -->"
END = "<!-- catalog:end -->"


def build_table() -> str:
    marketplace = json.loads((ROOT / ".claude-plugin" / "marketplace.json").read_text(encoding="utf-8"))
    rows = ["| Plugin | Version | Category | Description | Install |", "|---|---|---|---|---|"]
    for entry in marketplace["plugins"]:
        name = entry["name"]
        version = ""
        source = entry.get("source")
        if isinstance(source, str):
            manifest = ROOT / source / ".claude-plugin" / "plugin.json"
            version = json.loads(manifest.read_text(encoding="utf-8")).get("version", "")
            name_cell = f"[{name}]({source.removeprefix('./')})"
        else:
            name_cell = name
        rows.append(
            f"| {name_cell} | {version} | {entry.get('category', '')} | {entry.get('description', '')} "
            f"| `claude plugin install {name}@{marketplace['name']}` |"
        )
    return "\n".join(rows)


def main() -> int:
    text = README.read_text(encoding="utf-8")
    if START not in text or END not in text:
        print(f"README.md must contain the markers:\n{START}\n{END}")
        return 1
    before, rest = text.split(START, 1)
    _, after = rest.split(END, 1)
    updated = f"{before}{START}\n{build_table()}\n{END}{after}"

    if "--check" in sys.argv:
        if updated != text:
            print("::error file=README.md::Plugin catalog is stale. Run: python3 scripts/generate_catalog.py")
            return 1
        print("README catalog is up to date.")
        return 0
    README.write_text(updated, encoding="utf-8")
    print("README catalog regenerated.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
