#!/usr/bin/env python3
"""Regenerate the plugin version tables in README.md and docs/RELEASES.md.

Every plugin under plugins/ gets a row with the version the stable channel
serves (read at its pin, or "latest only") and the version in the tree, which
is what the latest channel serves (docs/specs/release-channels.md, R14, R16).

Usage:
  python3 scripts/generate_catalog.py          # rewrite both files
  python3 scripts/generate_catalog.py --check  # exit 1 if either is stale
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import channels  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent


def rows() -> list[dict]:
    stable = json.loads((ROOT / ".claude-plugin" / "marketplace.json").read_text(encoding="utf-8"))
    stable_versions = channels.stable_versions(ROOT, stable)
    out = []
    for name in channels.plugin_dirs(ROOT):
        manifest = channels.load_manifest(ROOT, name)
        metadata = manifest.get("metadata") or {}
        out.append({
            "name": name,
            "stable": stable_versions.get(name),
            "latest": manifest.get("version", ""),
            "category": metadata.get("category", ""),
            "description": manifest.get("description", ""),
            "compat": metadata.get("compat") or {},
            "dependencies": manifest.get("dependencies") or [],
        })
    return out


def readme_table(plugins: list[dict]) -> str:
    lines = ["| Plugin | Stable | Latest | Category | Description | Install |", "|---|---|---|---|---|---|"]
    for p in plugins:
        marketplace = channels.STABLE_NAME if p["stable"] else channels.LATEST_NAME
        lines.append(
            f"| [{p['name']}](plugins/{p['name']}) | {p['stable'] or 'latest only'} | {p['latest']} | {p['category']} "
            f"| {p['description']} | `claude plugin install {p['name']}@{marketplace}` |"
        )
    return "\n".join(lines)


def releases_table(plugins: list[dict]) -> str:
    lines = ["| Plugin | Stable | Latest | Depends on (compat range) |", "|---|---|---|---|"]
    for p in plugins:
        deps = ", ".join(f"{d} `{p['compat'].get(d, '?')}`" for d in p["dependencies"]) or "—"
        lines.append(f"| {p['name']} | {p['stable'] or 'latest only'} | {p['latest']} | {deps} |")
    return "\n".join(lines)


def splice(path: Path, block: str, table: str) -> tuple[str, str]:
    start, end = f"<!-- {block}:start (generated by scripts/generate_catalog.py, do not edit) -->", f"<!-- {block}:end -->"
    text = path.read_text(encoding="utf-8")
    if start not in text or end not in text:
        raise SystemExit(f"{path.relative_to(ROOT)} must contain the markers:\n{start}\n{end}")
    before, rest = text.split(start, 1)
    _, after = rest.split(end, 1)
    return text, f"{before}{start}\n{table}\n{end}{after}"


def main() -> int:
    plugins = rows()
    targets = [(ROOT / "README.md", "catalog", readme_table(plugins)),
               (ROOT / "docs" / "RELEASES.md", "versions", releases_table(plugins))]
    stale = []
    for path, block, table in targets:
        text, updated = splice(path, block, table)
        if updated == text:
            continue
        if "--check" in sys.argv:
            stale.append(path.relative_to(ROOT))
        else:
            path.write_text(updated, encoding="utf-8")
    if "--check" in sys.argv:
        for path in stale:
            print(f"::error file={path}::Plugin version table is stale. Run: python3 scripts/generate_catalog.py")
        if not stale:
            print("Plugin version tables are up to date.")
        return 1 if stale else 0
    print("Plugin version tables regenerated.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
